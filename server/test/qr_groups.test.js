// ==== [ DAFFA - BACKEND ] ==== //
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const sharp = require('sharp');
const { BasisDataJson } = require('../src/db');
const { buatAplikasi } = require('../src/app');
test('community consent, roles, private media, and persistence', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'shion-v4-'));
  let db = await new BasisDataJson(path.join(dir, 'database/account.json')).buka();
  const app = await buatAplikasi({ db, uploadsDir: path.join(dir, 'uploads'), ai: {}, limits: false });
  const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  t.after(async () => { await new Promise(r => server.close(r)); await db.tutup(); await fs.rm(dir, { recursive: true, force: true }); });
  const call = async (url, user, body, method = body === undefined ? 'GET' : 'POST') => {
    const r = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json', ...(user ? { Authorization: `Bearer ${user.token}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    const json = await r.json(); return { ...json, status: r.status };
  };
  const register = async name => (await call('/auth/register', null, { name, email: `${name}@example.com`, phone: '081234567890', password: 'secure-password' })).data;
  const alice = await register('Alice'), bob = await register('Bob'), outsider = await register('Other'), admin = await register('Admin');
  const aid = alice.state.user.id, bid = bob.state.user.id;
  await db.transaksi(d => { d.users.find(u => u.id === admin.state.user.id).role = 'admin'; });
  await t.test('QR poin umum dinonaktifkan; hanya QR setoran tersedia', async () => {
    assert.equal((await call('/points/qr', alice, {})).status, 404);
    assert.equal((await call('/admin/points/resolve', admin, { payload: 'shion:points:invalid' })).status, 404);
    assert.equal((await call('/admin/points/credit', admin, { payload: 'shion:points:invalid', amount: 7, requestId: 'credit-request-1' })).status, 404);
  });
  let gid, mid, mediaId;
  await t.test('invitation requires recipient consent and configured group admin approval', async () => {
    const created = await call('/groups', alice, { name: 'Sukabumi Hijau', description: 'Pilah bersama', requestId: 'create-group-1', approvalRequired: true });
    assert.equal(created.status, 201); gid = created.data.id; assert.equal(created.data.myRole, 'admin');
    const avatar = await sharp({ create: { width: 24, height: 24, channels: 3, background: '#009d20' } }).png().toBuffer();
    assert.equal((await call('/profile/photo', bob, { photoBase64: avatar.toString('base64') })).status, 200);
    assert.equal((await fetch(`${base}/profile/photo`, { headers: { Authorization: `Bearer ${bob.token}` } })).status, 200);
    assert.equal((await call(`/groups/${gid}/avatar`, alice, { photoBase64: avatar.toString('base64') })).status, 200);
    assert.equal((await fetch(`${base}/groups/${gid}/avatar`, { headers: { Authorization: `Bearer ${outsider.token}` } })).status, 403);
    assert.equal((await call('/groups', alice, { name: 'Sukabumi Hijau', requestId: 'create-group-1' })).data.id, gid);
    const username = db.baca(d => d.users.find(u => u.id === bid).username);
    assert.equal((await call(`/groups/${gid}/invite`, alice, { username })).status, 200);
    assert.equal((await call(`/groups/${gid}`, bob)).status, 403);
    const invite = (await call('/groups', bob)).data.invites[0];
    assert.equal((await call(`/group-invites/${invite.id}/respond`, outsider, { accept: true })).status, 404);
    assert.equal((await call(`/group-invites/${invite.id}/respond`, bob, { accept: true })).data.status, 'awaiting-approval');
    assert.equal((await call(`/groups/${gid}`, bob)).status, 403);
    const pending = (await call(`/groups/${gid}`, alice)).data.requests[0];
    assert.equal((await call(`/groups/${gid}/requests/${pending.id}`, admin, { accept: true })).status, 403);
    assert.equal((await call(`/groups/${gid}/requests/${pending.id}`, alice, { accept: true })).status, 200);
    assert.equal((await call(`/groups/${gid}`, bob)).data.group.myRole, 'member');
    assert.ok((await call(`/groups/${gid}`, bob)).data.messages.some(m => m.type === 'system' && m.body === 'Bob bergabung'));
    const othername = db.baca(d => d.users.find(u => u.id === outsider.state.user.id).username);
    await call(`/groups/${gid}/invite`, bob, { username: othername });
    const rejected = (await call('/groups', outsider)).data.invites[0];
    await call(`/group-invites/${rejected.id}/respond`, outsider, { accept: false });
    assert.equal((await call(`/groups/${gid}`, outsider)).status, 403);
  });
  await t.test('text idempotency, pin authorization, image/media isolation and video validation', async () => {
    const body = { body: 'Ayo pilah plastik.', requestId: 'chat-message-1' };
    const m = await call(`/groups/${gid}/messages`, bob, body); mid = m.data.id;
    assert.equal((await call(`/groups/${gid}/messages`, bob, body)).data.id, mid);
    assert.equal((await call(`/groups/${gid}/pin`, bob, { messageId: mid, pinned: true })).status, 403);
    assert.equal((await call(`/groups/${gid}/pin`, alice, { messageId: mid, pinned: true })).status, 200);
    assert.equal((await call(`/groups/${gid}`, bob)).data.pinned[0].id, mid);
    const reply = await call(`/groups/${gid}/messages`, alice, { body: 'Setuju, saya ikut memilah.', requestId: 'chat-reply-1', replyToId: mid });
    const replyView = (await call(`/groups/${gid}`, alice)).data.messages.find(m => m.id === reply.data.id);
    assert.equal(replyView.reply.body, 'Ayo pilah plastik.');
    assert.equal((await call(`/groups/${gid}/messages/${mid}`, outsider, {}, 'DELETE')).status, 403);
    assert.equal((await call(`/groups/${gid}/messages/${reply.data.id}`, alice, {}, 'DELETE')).status, 200);
    assert.equal((await call(`/groups/${gid}`, bob)).data.messages.find(m => m.id === reply.data.id).deletedForAll, true);
    const bytes = await sharp({ create: { width: 20, height: 20, channels: 3, background: '#009d20' } }).png().toBuffer();
    const upload = async (user, kind, buffer) => fetch(`${base}/groups/${gid}/media?kind=${kind}&requestId=media-request-1`, { method: 'POST', headers: { Authorization: `Bearer ${user.token}`, 'Content-Type': 'application/octet-stream' }, body: buffer });
    assert.equal((await upload(outsider, 'image', bytes)).status, 403);
    assert.equal((await upload(bob, 'video', bytes)).status, 400);
    const uploaded = await upload(bob, 'image', bytes); assert.equal(uploaded.status, 201); mediaId = (await uploaded.json()).data.id;
    assert.equal((await (await upload(bob, 'image', bytes)).json()).data.id, mediaId);
    assert.equal((await fetch(`${base}/groups/${gid}/media/${mediaId}`, { headers: { Authorization: `Bearer ${outsider.token}` } })).status, 403);
    const media = await fetch(`${base}/groups/${gid}/media/${mediaId}`, { headers: { Authorization: `Bearer ${alice.token}` } }); assert.equal(media.status, 200); assert.match(media.headers.get('Content-Type'), /image\/jpeg/); await media.arrayBuffer();
  });
  await t.test('last admin cannot abandon group; promote only by group admin; leave revokes media access', async () => {
    assert.equal((await call(`/groups/${gid}/promote`, bob, { userId: bid })).status, 403);
    assert.equal((await call(`/groups/${gid}/leave`, alice, {})).status, 409);
    assert.equal((await call(`/groups/${gid}/promote`, alice, { userId: bid })).status, 200);
    assert.equal((await call(`/groups/${gid}/settings`, bob, { approvalRequired: false }, 'PUT')).status, 200);
    assert.equal((await call(`/groups/${gid}/join`, outsider, {})).data.joined, true);
    assert.equal((await call(`/groups/${gid}/leave`, alice, {})).status, 200);
    assert.equal((await fetch(`${base}/groups/${gid}/media/${mediaId}`, { headers: { Authorization: `Bearer ${alice.token}` } })).status, 403);
  });
  await t.test('database has accounts only; user chat/media survive restart in session folders', async () => {
    const files = (await fs.readdir(path.join(dir, 'database'))).filter(x => !x.endsWith('.lock'));
    assert.deepEqual(files, ['account.json']);
    const username = db.baca(d => d.users.find(u => u.id === bid).username);
    const own = JSON.parse(await fs.readFile(path.join(dir, 'session', username, 'groupMessages.json')));
    assert.ok(own.some(message => message.id === mid)); assert.equal(own.length, 5);
    assert.equal((await fs.readdir(path.join(dir, 'session', username, 'media'))).length, 1);
    await db.tutup(); db = await new BasisDataJson(path.join(dir, 'database/account.json')).buka();
    assert.equal(db.baca(d => d.groupMessages.length), 6);
    assert.equal(db.baca(d => d.groups[0].members.find(m => m.userId === bid).role), 'admin');
    assert.equal(db.baca(d => d.ledger.filter(l => l.userId === aid).reduce((a, l) => a + l.delta, 0)), 0);
  });
});
